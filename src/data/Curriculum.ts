/**
 * Get content filtered by subject
 */
export function getContentBySubject(subject: string): ContentNode[] {
    return CONTENT_DB.filter(node => node.subject === subject);
}

/**
 * Get content filtered by grade level
 */
export function getContentByGrade(grade: number): ContentNode[] {
    return CONTENT_DB.filter(node => node.minGrade <= grade && node.maxGrade >= grade);
}

/**
 * Get content by Bloom's level
 */
export function getContentByBloomLevel(level: string): ContentNode[] {
    return CONTENT_DB.filter(node => node.bloomLevel === level);
}

/**
 * Get content by grade band (K-2, 3-5, 6-8, 9-12, College)
 */
export function getContentByGradeBand(band: string): ContentNode[] {
    const bandRanges: Record<string, [number, number]> = {
        "K-2": [0, 2],
        "3-5": [3, 5],
        "6-8": [6, 8],
        "9-12": [9, 12],
        "College": [13, 16]
    };

    const range = bandRanges[band];
    if (!range) return [];

    return CONTENT_DB.filter(node =>
        node.minGrade >= range[0] && node.maxGrade <= range[1]
    );
}

/**
 * Get content by standard reference (e.g., "NY-Regents", "NGSS", "NACE")
 */
export function getContentByStandard(standardPrefix: string): ContentNode[] {
    return CONTENT_DB.filter(node =>
        node.standardRef?.startsWith(standardPrefix)
    );
}

/**
 * Get random content node for testing
 */
export function getRandomContent(): ContentNode {
    return CONTENT_DB[Math.floor(Math.random() * CONTENT_DB.length)];
}

/**
 * Get content statistics
 */
export function getContentStats(): {
    total: number;
    bySubject: Record<string, number>;
    byGradeBand: Record<string, number>;
    byBloom: Record<string, number>;
} {
    const stats = {
        total: CONTENT_DB.length,
        bySubject: {} as Record<string, number>,
        byGradeBand: {} as Record<string, number>,
        byBloom: {} as Record<string, number>
    };

    CONTENT_DB.forEach(node => {
        // Count by subject
        stats.bySubject[node.subject] = (stats.bySubject[node.subject] || 0) + 1;

        // Count by bloom level
        stats.byBloom[node.bloomLevel] = (stats.byBloom[node.bloomLevel] || 0) + 1;

        // Count by grade band
        let band = "Unknown";
        if (node.minGrade <= 2) band = "K-2";
        else if (node.minGrade <= 5) band = "3-5";
        else if (node.minGrade <= 8) band = "6-8";
        else if (node.minGrade <= 12) band = "9-12";
        else band = "College";
        stats.byGradeBand[band] = (stats.byGradeBand[band] || 0) + 1;
    });

    return stats;
}

